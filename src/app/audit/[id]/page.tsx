import type { Metadata } from "next";
import { AuditFallback } from "@/components/dossier/audit-fallback";
import { DossierView } from "@/components/dossier/dossier-view";
import { loadAudit } from "@/lib/audit/store";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

export async function generateMetadata({
  params,
}: {
  params: Promise<{ id: string }>;
}): Promise<Metadata> {
  const { id } = await params;
  const audit = await loadAudit(id);

  if (!audit) {
    // Live audits live in the browser on serverless; metadata cannot know yet.
    return {
      title: "Prospect audit dossier",
      description: "A white-label prospect audit from Clinch.",
      alternates: { canonical: `/audit/${id}` },
      robots: { index: false, follow: false },
    };
  }

  if (id === "sample") {
    return {
      title: "Sample dossier — fictional demonstration",
      description:
        "A fictional demonstration audit generated by the Clinch engine. The prospect and agency are invented, and it is not a real client or result.",
      alternates: { canonical: "/audit/sample" },
      robots: { index: false, follow: false },
    };
  }

  return {
    title: `Prospect audit — ${audit.target.host}`,
    description: `${audit.stats.pagesCrawled} pages, ${audit.stats.checksRun} checks, ${audit.stats.issuesFound} findings. ${audit.target.host} scored ${audit.score}/100.`,
    alternates: { canonical: `/audit/${id}` },
    robots: { index: false, follow: false },
  };
}

export default async function AuditPage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;
  const audit = await loadAudit(id);

  if (!audit) {
    return <AuditFallback id={id} />;
  }

  return <DossierView audit={audit} isSample={id === "sample"} />;
}
